// Generates supabase/seed/demo-history.json: 6 months of invoices (paid or still open) for 12 customers,
// recurring expenses and the cash settings. Deterministic (seeded). All dates are offsets in days from the
// day the demo is seeded, so the story is the same whenever it is seeded:
// a cash shortfall in week 3 that the solver can cover.
// Usage: node scripts/gen-demo-history.mjs [openingBalancePaise]
import fs from 'node:fs';

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const r = rng(20261024);
const normal = () => {
  let s = 0;
  for (let i = 0; i < 6; i++) s += r();
  return s - 3; // roughly N(0, 0.7)
};

