// The first six already exist from the S4 demo (with their own open invoices); keep them as they are.
const ISSUE_OFFSETS = [-178, -158, -138, -118, -98, -78, -58, -38, -18];

const customers = CUSTOMERS.map(([key, name, entity_type, tier]) => ({
  key,
  name,
  entity_type,
  tier,
}));
const invoices = [];
let n = 0;
for (const [key, , , , mean, sd, typical] of CUSTOMERS) {
  for (const base of ISSUE_OFFSETS) {
    n++;
    const issue_off = base + Math.round((r() - 0.5) * 8);
    const due_off = issue_off + 30;
    const delay = Math.round(mean + normal() * sd * 1.4);
    const paid_off = due_off + delay;
    const taxable = Math.round((typical * 0.35 * (0.6 + r() * 0.8)) / 1000) * 1000 * 100;
    invoices.push({
      number: `HIS/26-27/${String(n).padStart(4, '0')}`,
      customer: key,
      taxable_paise: taxable,
      issue_off,
      due_off,
      // Paid in the past, otherwise still open.
      paid_off: paid_off <= -1 ? paid_off : null,
    });
  }
}

